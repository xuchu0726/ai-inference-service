import argparse
import csv
import statistics
from pathlib import Path
from typing import Any


def to_float(value: str | None) -> float | None:
    if value is None:
        return None
    value = str(value).strip()
    if value == "" or value.lower() == "none":
        return None
    try:
        return float(value)
    except ValueError:
        return None


def percentile(values: list[float], p: float) -> float | None:
    if not values:
        return None
    sorted_values = sorted(values)
    if len(sorted_values) == 1:
        return sorted_values[0]
    index = (len(sorted_values) - 1) * p
    lower = int(index)
    upper = min(lower + 1, len(sorted_values) - 1)
    weight = index - lower
    return sorted_values[lower] * (1 - weight) + sorted_values[upper] * weight


def summarize_values(prefix: str, values: list[float], summary: dict[str, Any]) -> None:
    if not values:
        summary[f"{prefix}_avg"] = None
        summary[f"{prefix}_p50"] = None
        summary[f"{prefix}_p95"] = None
        summary[f"{prefix}_min"] = None
        summary[f"{prefix}_max"] = None
        return

    summary[f"{prefix}_avg"] = round(statistics.mean(values), 6)
    summary[f"{prefix}_p50"] = round(percentile(values, 0.50), 6)
    summary[f"{prefix}_p95"] = round(percentile(values, 0.95), 6)
    summary[f"{prefix}_min"] = round(min(values), 6)
    summary[f"{prefix}_max"] = round(max(values), 6)


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def write_summary(path: Path, summary: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)

    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(summary.keys()))
        writer.writeheader()
        writer.writerow(summary)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Analyze vLLMBackend benchmark CSV."
    )
    parser.add_argument(
        "--input",
        default="results/vllm_backend_benchmark.csv",
        help="Input benchmark CSV generated by benchmark_vllm_backend.py.",
    )
    parser.add_argument(
        "--output",
        default="results/vllm_backend_benchmark_summary.csv",
        help="Output summary CSV.",
    )
    args = parser.parse_args()

    input_path = Path(args.input)
    output_path = Path(args.output)

    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")

    rows = read_rows(input_path)

    total_requests = len(rows)
    success_rows = [r for r in rows if str(r.get("ok", "")).lower() == "true"]
    failed_rows = [r for r in rows if str(r.get("ok", "")).lower() != "true"]

    client_latencies = [
        value
        for value in (to_float(r.get("client_latency_seconds")) for r in success_rows)
        if value is not None
    ]

    server_latencies = [
        value
        for value in (to_float(r.get("server_latency_seconds")) for r in success_rows)
        if value is not None
    ]

    tokens_per_second = [
        value
        for value in (to_float(r.get("tokens_per_second")) for r in success_rows)
        if value is not None
    ]

    input_tokens = [
        value
        for value in (to_float(r.get("input_tokens")) for r in success_rows)
        if value is not None
    ]

    output_tokens = [
        value
        for value in (to_float(r.get("output_tokens")) for r in success_rows)
        if value is not None
    ]

    concurrencies = sorted(
        {
            int(float(r["concurrency"]))
            for r in rows
            if r.get("concurrency") not in (None, "")
        }
    )

    backends = sorted({r.get("backend", "") for r in success_rows if r.get("backend")})
    models = sorted({r.get("model_name", "") for r in success_rows if r.get("model_name")})
    devices = sorted({r.get("device", "") for r in success_rows if r.get("device")})

    summary: dict[str, Any] = {
        "input_file": str(input_path),
        "total_requests": total_requests,
        "successful_requests": len(success_rows),
        "failed_requests": len(failed_rows),
        "error_rate": round(len(failed_rows) / total_requests, 6)
        if total_requests
        else None,
        "concurrency_values": "|".join(str(x) for x in concurrencies),
        "backend_values": "|".join(backends),
        "model_name_values": "|".join(models),
        "device_values": "|".join(devices),
    }

    summarize_values("client_latency_seconds", client_latencies, summary)
    summarize_values("server_latency_seconds", server_latencies, summary)
    summarize_values("tokens_per_second", tokens_per_second, summary)
    summarize_values("input_tokens", input_tokens, summary)
    summarize_values("output_tokens", output_tokens, summary)

    write_summary(output_path, summary)

    print("===== VLLM BACKEND BENCHMARK ANALYSIS =====")
    for key, value in summary.items():
        print(f"{key}: {value}")

    print()
    print(f"saved_summary_csv: {output_path}")


if __name__ == "__main__":
    main()
